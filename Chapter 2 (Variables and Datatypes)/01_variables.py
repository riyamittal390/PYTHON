# A variable is the name given to a memory location in a program.

a = 5
b = 10
c = a + b
print(c)

# a, b, c are variables









# Rules for defining variable names

# 1. A variable name can contain alphabets, digits, and underscores.
# 2. A variable name can only start with an alphabet or underscore.
# 3. A variable name can't start with a digit.
# 4. No while space is allowed to be used inside a variable name.