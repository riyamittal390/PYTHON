# "While" loop executes only when the given condition is True.
# In while loops, the condition is checked first. If it evaluates to true, the body of the loop is executed otherwise not.
# If the loop is entered, the process of condition check and execution is continued until the condition becomes False.
# If the condition never becomes False, the loop keeps getting executed and will become an infinite loop.

i = 0
while (i < 11):
    print("Riya")
    i = i + 1